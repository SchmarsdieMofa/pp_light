import { expect, test } from "@playwright/test";
import { choose, closeTask, createProjectViaUi, login } from "./fixtures";

test("manages project and task appointments and shows them in all calendar views", async ({ page }) => {
  await login(page);
  const board = await createProjectViaUi(page, "Terminplanung", "appt");
  const input = page.getByLabel("Neue Aufgabe in Offen");
  await input.fill("Entwurf vorbereiten");
  await input.press("Enter");
  await page.getByRole("link", { name: "Termine", exact: true }).click();
  await page.getByRole("button", { name: "Termin anlegen" }).click();
  const form = page.getByRole("form", { name: "Neuer Termin" });
  await form.getByLabel("Titel", { exact: true }).fill("Projektauftakt");
  await form.getByLabel("Beginn").fill("2030-01-15T09:00");
  await form.getByLabel("Ende").fill("2030-01-15T10:00");
  await form.getByLabel("Ort (optional)").fill("Raum Berlin");
  await form.getByRole("button", { name: "Speichern", exact: true }).click();
  await expect(form).toBeHidden();
  const entry = page.getByRole("listitem").filter({ hasText: "Projektauftakt" });
  await expect(entry).toContainText("15.01.2030, 09:00");
  await page.reload();
  await expect(entry).toContainText("Raum Berlin");
  await entry.getByRole("button", { name: "Bearbeiten", exact: true }).click();
  const edit = page.getByRole("form", { name: "Termin bearbeiten" });
  await edit.getByLabel("Titel", { exact: true }).fill("Projektauftakt geplant");
  await choose(edit.getByLabel("Aufgabe (optional)"), "1 Entwurf vorbereiten");
  await edit.getByRole("button", { name: "Speichern", exact: true }).click();
  await expect(edit).toBeHidden();

  await page.goto("/calendar?date=2030-01-15");
  const day = page.getByRole("gridcell", { name: /^Dienstag, 15\. Januar 2030/ });
  await expect(day.getByRole("link", { name: /09:00 Projektauftakt geplant/ })).toBeVisible();
  await page.getByRole("link", { name: "Woche", exact: true }).click();
  await expect(page.getByRole("region", { name: "Dienstag, 15. Januar 2030" })).toContainText("Projektauftakt geplant");
  await page.getByRole("link", { name: "Liste", exact: true }).click();
  await page.getByRole("link", { name: /09:00 Projektauftakt geplant/ }).click();
  await expect(page).toHaveURL(/\/appointments#/);

  await page.goto(board);
  await page.getByRole("region", { name: "Offen" }).getByRole("link", { name: /Entwurf vorbereiten/ }).click();
  const panel = page.getByRole("dialog", { name: "Aufgabe" });
  await expect(panel.getByRole("region", { name: "Termine" })).toContainText("Projektauftakt geplant");
  await panel.getByRole("button", { name: "Termin anlegen" }).click();
  const taskForm = panel.getByRole("form", { name: "Neuer Termin" });
  await taskForm.getByLabel("Titel", { exact: true }).fill("Entwurf besprechen");
  await taskForm.getByLabel("Beginn").fill("2030-01-16T11:00");
  await taskForm.getByLabel("Ende").fill("2030-01-16T10:00");
  await taskForm.getByRole("button", { name: "Speichern", exact: true }).click();
  await expect(taskForm.getByRole("alert")).toContainText("Das Ende muss nach dem Beginn liegen.");
  await taskForm.getByLabel("Ende").fill("2030-01-16T12:00");
  await taskForm.getByRole("button", { name: "Speichern", exact: true }).click();
  await expect(taskForm).toBeHidden();
  await expect(panel.getByRole("region", { name: "Termine" })).toContainText("Entwurf besprechen");
  await closeTask(page);
  await page.getByRole("link", { name: "Termine", exact: true }).click();
  const taskEntry = page.getByRole("listitem").filter({ hasText: "Entwurf besprechen" });
  await taskEntry.getByRole("button", { name: "Löschen", exact: true }).click();
  await taskEntry.getByRole("button", { name: "Endgültig löschen", exact: true }).click();
  await expect(taskEntry).toHaveCount(0);
});
